fn main() {
    let number = 6;

    if number % 4 = 0 {
        println!("Number is divided by 4");
    } else if number % 3 = 0 {
        println!("Number is divided by 3");
    } else if number % 2 = 0 {
        println!("Number is divided by 2");
    } else {
        println!("Number is not divided by 4,3or 2");
    }
}
